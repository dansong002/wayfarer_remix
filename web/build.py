"""Builds the phone and web version of Wayfarer Remix into a folder of static files.

The web version is the same UI as the desktop app (wayfarer/ui). This script copies it, switches it to the browser
backend (webapi.js) by rewriting mode.js, and adds a service worker so it works offline once installed.

  python web/build.py _site [version]

Serve the folder over HTTPS (GitHub Pages does this) and open it on a phone. Nothing here needs network access.
"""

import hashlib
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UI = ROOT / "wayfarer" / "ui"
# Desktop-only files that the web version doesn't need.
SKIP = {"icon.ico"}

SERVICE_WORKER = """// Generated by web/build.py. Keeps every file of this version on the device, so Wayfarer opens offline.
"use strict";
const CACHE = %(cache)s;
const FILES = %(files)s;
self.addEventListener("install", e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith("wayfarer-") && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener("fetch", e => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== location.origin) return;
  e.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req)));
});
"""


def build(out: Path, version: str = "web") -> list[str]:
    """Write the web build to `out` and return the list of files the service worker keeps."""
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(UI, out, ignore=lambda folder, names: [n for n in names if n in SKIP or n == "__pycache__"])
    (out / "mode.js").write_text(
        f'"use strict";\n// Web build of Wayfarer Remix, made by web/build.py.\nwindow.WAYFARER_WEB = {json.dumps({"version": version})};\n',
        encoding="utf-8",
    )
    files = sorted(p.relative_to(out).as_posix() for p in out.rglob("*") if p.is_file())
    digest = hashlib.sha256()
    for name in files:
        digest.update(name.encode())
        digest.update((out / name).read_bytes())
    cached = ["./", *files]
    (out / "sw.js").write_text(
        SERVICE_WORKER % {"cache": json.dumps(f"wayfarer-{digest.hexdigest()[:12]}"), "files": json.dumps(cached, indent=2)},
        encoding="utf-8",
    )
    # GitHub Pages: serve the files as they are, without Jekyll.
    (out / ".nojekyll").write_text("", encoding="utf-8")
    return cached


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    target = Path(sys.argv[1])
    kept = build(target, sys.argv[2] if len(sys.argv) > 2 else "web")
    print(f"Built {len(kept)} files into {target}")
